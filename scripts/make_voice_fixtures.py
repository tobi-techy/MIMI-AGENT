"""Make the synthetic voice-note fixtures in ``eval/voice/clips/``.

    SPITCH_API_KEY=... python scripts/make_voice_fixtures.py          # missing clips only
    SPITCH_API_KEY=... python scripts/make_voice_fixtures.py --force  # all of them

Every clip is synthetic-generated: the text in ``eval/voice/clips.jsonl`` is
spoken by a Spitch text-to-speech system voice (no real person's voice, no
recording of anyone), then ffmpeg adds synthetic market noise (pink and
brown noise, a low generator hum and, for "heavy", two short horn-like
tones; all generated by ffmpeg, no sampled sound) and encodes it the way
WhatsApp sends a voice note: mono Ogg/Opus at 16 kbps. Two clips are MP3
and M4A to cover the other accepted formats. Each file carries a
``comment=synthetic-generated ...`` tag.

Noise levels: ``none``; ``light`` (noise about 18 dB under the speech);
``heavy`` (about 8 dB under, plus the horn).
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from mimi.voice.tts import SpitchSpeech  # noqa: E402

VOICE_DIR = ROOT / "eval" / "voice"
MANIFEST = VOICE_DIR / "clips.jsonl"
COMMENT = "synthetic-generated: Spitch TTS system voice plus ffmpeg noise; no real voice"

# (noise amplitude, hum amplitude, horn) per level; speech peaks near 0.9.
LEVELS = {"none": None, "light": (0.022, 0.01, False), "heavy": (0.07, 0.03, True)}
ENCODE = {
    "ogg": ["-c:a", "libopus", "-b:a", "16k", "-ar", "16000"],
    "mp3": ["-c:a", "libmp3lame", "-b:a", "32k", "-ar", "16000"],
    "m4a": ["-c:a", "aac", "-b:a", "32k", "-ar", "16000"],
}


def mix(speech_wav: Path, out: Path, noise: str, fmt: str, seed: int) -> None:
    level = LEVELS[noise]
    pad = "adelay=400:all=1,apad=pad_dur=0.5"
    if level is None:
        graph = f"[0:a]aformat=channel_layouts=mono,{pad}[out]"
        inputs = ["-i", str(speech_wav)]
    else:
        amp, hum, horn = level
        graph = (
            f"[0:a]aformat=channel_layouts=mono,{pad}[s];"
            f"[1:a]volume={amp}[n1];[2:a]lowpass=f=400,volume={amp * 1.5}[n2];"
            f"[3:a]volume={hum}[h];"
        )
        mix_in = "[s][n1][n2][h]"
        count = 4
        if horn:
            graph += (
                "[4:a]volume='if(between(t,0.9,1.3)+between(t,1.5,1.8),0.12,0)':eval=frame[hn];"
            )
            mix_in += "[hn]"
            count = 5
        graph += f"{mix_in}amix=inputs={count}:duration=first:normalize=0[out]"
        inputs = [
            "-i",
            str(speech_wav),
            "-f",
            "lavfi",
            "-i",
            f"anoisesrc=color=pink:amplitude=1:seed={seed}:sample_rate=24000",
            "-f",
            "lavfi",
            "-i",
            f"anoisesrc=color=brown:amplitude=1:seed={seed + 1}:sample_rate=24000",
            "-f",
            "lavfi",
            "-i",
            "sine=frequency=100:sample_rate=24000",
        ]
        if horn:
            inputs += ["-f", "lavfi", "-i", "sine=frequency=440:sample_rate=24000"]
    cmd = [
        "ffmpeg",
        "-v",
        "error",
        "-y",
        *inputs,
        "-filter_complex",
        graph,
        "-map",
        "[out]",
        "-ac",
        "1",
        *ENCODE[fmt],
        "-map_metadata",
        "-1",
        "-metadata",
        f"comment={COMMENT}",
        str(out),
    ]
    subprocess.run(cmd, check=True)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--only", nargs="*", default=None)
    args = ap.parse_args(argv)
    key = os.environ.get("SPITCH_API_KEY", "").strip()
    if not key:
        print("SPITCH_API_KEY is not set", file=sys.stderr)
        return 2
    tts = SpitchSpeech(api_key=key)
    rows = [json.loads(x) for x in MANIFEST.read_text(encoding="utf-8").splitlines() if x]
    for i, row in enumerate(rows):
        out = VOICE_DIR / row["file"]
        if args.only and row["id"] not in args.only:
            continue
        if out.exists() and not args.force:
            continue
        out.parent.mkdir(parents=True, exist_ok=True)
        wav = tts.generate(
            row["reference"], voice=row["tts"]["voice"], language=row["tts"]["language"]
        )
        with tempfile.TemporaryDirectory() as tmp:
            src = Path(tmp) / "speech.wav"
            src.write_bytes(wav)
            mix(src, out, row["noise"], out.suffix.lstrip("."), seed=1000 + i)
        print(f"{row['id']}: {out.relative_to(ROOT)} {out.stat().st_size} bytes")
    print(f"speech calls: {tts.calls}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
