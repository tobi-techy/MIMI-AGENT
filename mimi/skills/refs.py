"""References generated from the code that is the truth for them.

A word list the model reads (product nicknames, number words, day words,
bank alert layouts, the overdue ladder) must say exactly what the code
matches, or the model and the code disagree. So these reference files are
written from the code by ``python -m mimi.skills refs`` and a test fails
when one drifts. Hand-written references (reply wording) live beside them.
"""

from __future__ import annotations

from collections.abc import Callable
from pathlib import Path

HEADER = ("<!-- Generated by python -m mimi.skills refs from {src}. Do not edit by hand: "
          "change the code, then regenerate. -->\n")


def product_nicknames() -> str:
    from mimi.orders.catalogue import FAMILIES, UNIT_SYNONYMS

    out = [HEADER.format(src="mimi/orders/catalogue.py"), "# Product nicknames",
           "", "What shops call each product family, and the size or pack words that pick a "
           "variant. Code does the matching; this list is for reading a puzzling word.", "",
           "| Family | Shops say | Variant words |", "|---|---|---|"]
    for f in FAMILIES:
        variants = "; ".join(f"{sku}: {', '.join(ws)}" for sku, ws in f.variants.items() if ws)
        out.append(f"| {f.label} | {', '.join(f.words)} | {variants or '-'} |")
    out += ["", "## Unit words", "", "| Unit | Shops say |", "|---|---|"]
    units: dict[str, list[str]] = {}
    for w, u in UNIT_SYNONYMS.items():
        units.setdefault(u, []).append(w)
    for u, ws in sorted(units.items()):
        out.append(f"| {u} | {', '.join(ws)} |")
    return "\n".join(out) + "\n"


def number_words() -> str:
    from mimi.orders.words import NUMBER_WORDS, ONE_WORDS
    from mimi.voice import promise as vp

    out = [HEADER.format(src="mimi/orders/words.py and mimi/voice/promise.py"),
           "# Number words", "",
           "Quantities on orders (`mimi.orders.words.NUMBER_WORDS`), English, Pidgin, Yoruba, "
           "Hausa and Igbo, as code reads them after folding (lower case, no tone marks).", "",
           "| Word | Number |", "|---|---|"]
    out += [f"| {w} | {n} |" for w, n in NUMBER_WORDS.items()]
    out += ["", f"A single unit: {', '.join(ONE_WORDS)}.", "",
            "## Money words in voice notes (`mimi.voice.promise`)", "",
            "Yoruba: " + ", ".join(f"{w}={n}" for w, n in vp._YO_NUM.items()), "",
            "Hausa: " + ", ".join(f"{w}={n}" for w, n in vp._HA_NUM.items()), "",
            "Igbo: " + ", ".join(f"{w}={n}" for w, n in vp._IG_UNITS.items())]
    return "\n".join(out) + "\n"


def day_words() -> str:
    from mimi.voice import promise as vp

    names = ("Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday")
    by_day: dict[int, list[str]] = {}
    for w, d in vp._WEEKDAYS.items():
        by_day.setdefault(d, []).append(w)
    out = [HEADER.format(src="mimi/voice/promise.py"), "# Day words", "",
           "The day words followup_hours reads (folded: lower case, no tone marks).", "",
           "| Day | Words |", "|---|---|"]
    out += [f"| {names[d]} | {', '.join(ws)} |" for d, ws in sorted(by_day.items())]
    out += ["", "| Meaning | Words (regex) |", "|---|---|",
            f"| today | `{vp._TODAY}` |", f"| tomorrow | `{vp._TOMORROW}` |",
            f"| day after tomorrow | `{vp._DAY_AFTER}` |", f"| next week | `{vp._NEXT_WEEK}` |",
            f"| month end | `{vp._MONTH_END}` |", f"| past (not a promise) | `{vp._PAST}` |"]
    return "\n".join(out) + "\n"


def bank_alert_formats() -> str:
    from mimi.proof.banks import BANKS

    out = [HEADER.format(src="mimi/proof/banks.py"), "# Bank alert formats", "",
           "The fictional banks of the synthetic world (no real bank is named in this repo). "
           "parse_bank_alert reads the SMS layout; check_payment_screenshot reads app receipts.",
           "", "| Bank | Layout | Reference looks like | Time printed as | Also written |",
           "|---|---|---|---|---|"]
    for b in BANKS:
        out.append(f"| {b.name} | {b.layout} | `{b.reference_re}` | "
                   f"{', '.join(f'`{f}`' for f in b.time_formats)} | {', '.join(b.aliases)} |")
    out += ["", "An SMS alert reads, line by line (example, synthetic):", "", "```",
            "Ironleaf Bank Debit Alert", "Acct: 01******4821", "Amt: NGN84,500.00 DR",
            "Desc: TRF TO CORAL LANE TRADING/IL/TRF/204918377", "Time: 27/10/2026 14:02",
            "Avl Bal: NGN12,300.00", "```", "",
            "A debit alert on the shop's phone is a claim. Only the distributor's bank feed "
            "(check_payment) makes a payment verified."]
    return "\n".join(out) + "\n"


def overdue_ladder() -> str:
    from mimi.harness.collector import ladder

    out = [HEADER.format(src="mimi/harness/collector.py (ladder)"), "# Overdue ladder", "",
           "Code picks the step and tone from days overdue (get_invoices returns both).", "",
           "| Days overdue | Step | Tone |", "|---|---|---|"]
    for days in (0, 1, 2, 3, 6, 7, 13, 14, 30):
        step, tone = ladder(days)
        out.append(f"| {days} | {step} | {tone} |")
    out += ["", "Step 7 tells the rep; step 14 is the owner's decision. One reminder a day at "
            "most, and a firm reminder or one over the owner's limit waits for approval "
            "(Go policy)."]
    return "\n".join(out) + "\n"


def how_review_works() -> str:
    from mimi.credit import review as r

    out = [HEADER.format(src="mimi/credit/review.py"), "# How the credit review works", "",
           f"Recommender {r.RECOMMENDER_VERSION}, all in code: the model never scores a shop.",
           "", f"* Window: the last {r.WINDOW_DAYS} days of the book.",
           f"* At least {r.MIN_VERIFIED} verified payments before any support.",
           f"* On time {r.SUPPORT_ON_TIME}% or better can support a rise; under "
           f"{r.POOR_ON_TIME}% counts against it.",
           f"* An invoice more than {r.LATE_DAYS} days overdue counts against it.",
           f"* Shelf photo: a count over {r.SHELF_SLACK}x what the book explains (or "
           f"{r.SHELF_SLACK_PIECES}+ pieces) is flagged for the owner, never trusted alone.",
           "", "The owner sets every limit. A shop never hears its score or reasons."]
    return "\n".join(out) + "\n"


GENERATED: dict[str, Callable[[], str]] = {
    "order-intake/references/product-nicknames.md": product_nicknames,
    "order-intake/references/number-words.md": number_words,
    "promise-to-pay/references/day-words.md": day_words,
    "fake-alert-check/references/bank-alert-formats.md": bank_alert_formats,
    "collections/references/overdue-ladder.md": overdue_ladder,
    "chase/references/overdue-ladder.md": overdue_ladder,
    "credit-review/references/how-review-works.md": how_review_works,
}


def write_all(root: Path) -> list[str]:
    changed = []
    for rel, fn in GENERATED.items():
        path = root / rel
        text = fn()
        if not path.exists() or path.read_text(encoding="utf-8") != text:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            changed.append(rel)
    return changed


def drift(root: Path) -> list[str]:
    return [rel for rel, fn in GENERATED.items()
            if not (root / rel).is_file() or (root / rel).read_text(encoding="utf-8") != fn()]
